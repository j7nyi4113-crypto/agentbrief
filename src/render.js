import { LABELS } from './ecosystems.js';

export const BEGIN = '<!-- agentbrief:begin -->';
export const END = '<!-- agentbrief:end -->';

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function metaLine(facts) {
  const meta = {
    v: 1,
    commands: facts.commands.map((c) => ({ key: c.key, cmd: c.cmd, src: c.src })),
    dirs: facts.layout.filter((l) => l.kind === 'dir').map((l) => l.path),
  };
  return `<!-- agentbrief:meta ${JSON.stringify(meta)} -->`;
}

function stackLine(facts) {
  const parts = [...facts.stack];
  if (facts.totalFiles) parts.push(`${facts.totalFiles.toLocaleString('en-US')} files`);
  return parts.join(' · ');
}

export function renderBlock(facts) {
  const lines = [];
  lines.push(BEGIN);
  lines.push(metaLine(facts));
  lines.push('');
  lines.push('## Repo facts');
  lines.push('');
  lines.push(
    '<!-- Generated by agentbrief from the repository. Do not edit by hand: run `agentbrief update`. -->',
  );
  lines.push('');
  lines.push(`**Stack:** ${stackLine(facts)}`);

  if (facts.commands.length) {
    lines.push('');
    lines.push('### Commands');
    lines.push('');
    lines.push('| Task | Command | Source |');
    lines.push('| --- | --- | --- |');
    for (const c of facts.commands) {
      lines.push(`| ${LABELS[c.key] || c.key} | \`${esc(c.cmd)}\` | \`${esc(c.src)}\` |`);
    }
  }

  const dirs = facts.layout.filter((l) => l.kind === 'dir');
  if (dirs.length) {
    lines.push('');
    lines.push('### Layout');
    lines.push('');
    lines.push('| Path | Contents |');
    lines.push('| --- | --- |');
    for (const d of dirs) {
      const hint = d.hint ? `${d.hint} · ` : '';
      lines.push(`| \`${esc(d.path)}/\` | ${hint}${d.files.toLocaleString('en-US')} ${d.files === 1 ? 'file' : 'files'} |`);
    }
  }

  if (facts.workspaces?.length) {
    lines.push('');
    lines.push(`**Workspaces:** ${facts.workspaces.map((w) => `\`${w}\``).join(', ')}`);
  }

  if (facts.ci.length) {
    lines.push('');
    lines.push('### CI');
    lines.push('');
    for (const w of facts.ci) {
      const when = w.triggers.length ? `on ${w.triggers.join(', ')}` : 'on every push';
      const runs = w.runs.length ? ` — ${w.runs.map((r) => `\`${r}\``).join(', ')}` : '';
      lines.push(`- \`${w.file}\` runs ${when}${runs}`);
    }
  }

  if (facts.conventions.length) {
    lines.push('');
    lines.push('### Conventions');
    lines.push('');
    for (const conv of facts.conventions) {
      lines.push(`- **${conv.name}:** ${conv.detail}`);
    }
  }

  lines.push(END);
  return lines.join('\n');
}

export function renderScaffold() {
  return [
    '# AGENTS.md',
    '',
    'Instructions for coding agents working in this repository.',
    'The **Repo facts** block at the bottom is generated by [agentbrief](https://github.com/j7nyi4113-crypto/agentbrief)',
    'and verified in CI. Run `agentbrief update` after changing commands or moving files.',
    'Everything above the block is yours — that is the part no tool can write for you.',
    '',
    '## What this is',
    '',
    '<!-- One paragraph: what it does, who uses it, what "done" means. Agents are bad at guessing intent. -->',
    '',
    '## How to work here',
    '',
    '<!-- Conventions that live in nobody\'s config file: naming, error handling, what you refuse to merge. -->',
    '',
    '## Traps',
    '',
    '<!-- What will bite an agent: generated files, ordering constraints, flaky tests, required env vars,',
    '     commands that look safe but are not. -->',
    '',
  ].join('\n');
}

export function renderFile(facts, existing) {
  const block = renderBlock(facts);
  if (existing && existing.includes(BEGIN)) {
    const head = existing.slice(0, existing.indexOf(BEGIN));
    const endAt = existing.indexOf(END);
    const tail = endAt === -1 ? '' : existing.slice(endAt + END.length);
    return head + block + tail;
  }
  if (existing) {
    return `${existing.replace(/\s*$/, '')}\n\n${block}\n`;
  }
  return `${renderScaffold()}\n${block}\n`;
}
